"""
Per-Model Visualizations for Chain Linking Experiments.

This module generates "Error by Distance" plots for individual models,
allowing analysis of specific model behaviors rather than just population averages.
Called from visualize_paper_v3.py.

REQUIRED FILES (per dist_* directory):
For each scenario, the following CSV files are needed:

Scenario 1 (New Model + New Data):
  - validation_fixed.csv
  - validation_concurrent.csv
  - random_simple_fixed.csv (optional, for baseline)

Scenario 2 (Old Model + New Data):
  - validation_old_model_new_data_fixed.csv
  - validation_old_model_new_data_concurrent.csv
  - random_simple_old_model_fixed.csv (optional)

Scenario 3 (New Model + Old Data):
  - validation_new_model_old_data_fixed.csv
  - validation_new_model_old_data_concurrent.csv
  - random_simple_new_model_old_data_fixed.csv (optional)

These files are generated by chain_linking_v2.py or chain_linking_parallel_b.py.
If files are missing, the experiments may have been run with an older code version.
"""

from __future__ import annotations

import json
from pathlib import Path
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

# Shared plotting styles from visualize_paper_v3
COLORS = {
    'fixed': '#27ae60',           # Green
    'concurrent': '#c0392b',      # Red
    'random_simple': '#3498db',   # Blue
}

MARKERS = {
    'fixed': 'o',
    'concurrent': '^',
    'random_simple': 's',
}

SCENARIOS = {
    'new_model_new_data': {
        'title': 'Scenario 1: New Model + New Dataset',
        'file_suffix': 'validation', 
        'random_simple_file': 'random_simple_fixed.csv'
    },
    'old_model_new_data': {
        'title': 'Scenario 2: Old Model + New Dataset',
        'file_suffix': 'validation_old_model_new_data',
        'random_simple_file': 'random_simple_old_model_fixed.csv'
    },
    'new_model_old_data': {
        'title': 'Scenario 3: New Model + Old Datasets',
        'file_suffix': 'validation_new_model_old_data',
        'random_simple_file': 'random_simple_new_model_old_data_fixed.csv'
    },
}

def load_per_model_data(output_dir: Path) -> tuple[dict, dict]:
    """
    Scans output_dir for dist_* folders and loads per-model CSVs.
    
    Returns:
        data: nested dictionary
            data[scenario][model_name] = {
                'fixed': {dist: error, ...},
                'concurrent': {dist: error, ...},
                'random_simple': {dist: error, ...}
            }
        diagnostics: dict with file counts and missing file info
    """
    data = {s: {} for s in SCENARIOS}
    diagnostics = {
        'dist_dirs_found': 0,
        'validation_files_found': 0,
        'validation_files_missing': [],
        'random_files_found': 0,
    }
    
    # Find all distance directories
    dist_dirs = sorted(list(output_dir.glob("dist_*")))
    diagnostics['dist_dirs_found'] = len(dist_dirs)
    
    for dist_dir in dist_dirs:
        try:
            parts = dist_dir.name.split('_')
            distance = int(parts[1])
        except (IndexError, ValueError):
            continue
            
        # Load data for each scenario
        for scenario_key, info in SCENARIOS.items():
            suffix = info['file_suffix']
            
            for method in ['fixed', 'concurrent']:
                csv_name = f"{suffix}_{method}.csv"
                csv_path = dist_dir / csv_name
                
                if not csv_path.exists():
                    # Record missing file (only once per unique file pattern)
                    missing_key = f"{csv_name} (dist_*/{csv_name})"
                    if missing_key not in diagnostics['validation_files_missing']:
                        diagnostics['validation_files_missing'].append(missing_key)
                    continue
                
                diagnostics['validation_files_found'] += 1
                    
                try:
                    df = pd.read_csv(csv_path)
                    
                    # Check for error column
                    # Priority: gp_irt_error > irt_error > simple_random_error
                    err_col = None
                    for col in ['gp_irt_error', 'irt_error']:
                        if col in df.columns:
                            err_col = col
                            break
                    
                    if not err_col:
                        continue
                        
                    # Handle multiple rows per model (Scenario 3: multiple datasets)
                    # We average the error across datasets for the model at this distance
                    if 'model_name' in df.columns:
                        grouped = df.groupby('model_name')[err_col].mean()
                        
                        for model_name, error in grouped.items():
                            if model_name not in data[scenario_key]:
                                data[scenario_key][model_name] = {
                                    'fixed': {}, 'concurrent': {}, 'random_simple': {}
                                }
                            data[scenario_key][model_name][method][distance] = error * 100 # Convert to %
                            
                except Exception as e:
                    print(f"    ⚠ Error reading {csv_path.name}: {e}")

            # Load Random Baseline (Simple)
            rand_csv_name = info['random_simple_file']
            rand_csv_path = dist_dir / rand_csv_name
            
            if rand_csv_path.exists():
                diagnostics['random_files_found'] += 1
                try:
                    df = pd.read_csv(rand_csv_path)
                    if 'simple_random_error_mean' in df.columns and 'model_name' in df.columns:
                         grouped = df.groupby('model_name')['simple_random_error_mean'].mean()
                         for model_name, error in grouped.items():
                            if model_name in data[scenario_key]: # Only add if model exists in main results
                                data[scenario_key][model_name]['random_simple'][distance] = error * 100
                except Exception:
                    pass

    return data, diagnostics

def plot_per_model_error_by_distance(output_dir: Path, config: dict):
    """Generates one plot per model showing error vs distance."""
    print("\n   Generating per-model visualizations...")
    
    # Load data with diagnostics
    data, diagnostics = load_per_model_data(output_dir)
    
    # Print diagnostics
    print(f"    📊 Found {diagnostics['dist_dirs_found']} distance directories")
    print(f"    📊 Found {diagnostics['validation_files_found']} validation CSV files")
    print(f"    📊 Found {diagnostics['random_files_found']} random baseline CSV files")
    
    # Check if validation files are missing
    if diagnostics['validation_files_found'] == 0:
        print("\n    ⚠️  NO VALIDATION CSV FILES FOUND!")
        print("    ⚠️  Per-model visualizations require validation_*.csv files.")
        print("\n    Required files (in each dist_* directory):")
        print("      - validation_fixed.csv")
        print("      - validation_concurrent.csv")
        print("      - validation_old_model_new_data_fixed.csv")
        print("      - validation_new_model_old_data_fixed.csv")
        print("\n    These files are generated by newer versions of:")
        print("      - chain_linking_v2.py")
        print("      - chain_linking_parallel_b.py")
        print("\n    Solution: Re-run experiments with the current code version,")
        print("    or use data from v8_lamdas_parallel_new_exps_100 which has these files.")
        return
    
    if diagnostics['validation_files_missing']:
        print(f"\n    ⚠️  Some validation files missing:")
        for missing in diagnostics['validation_files_missing'][:5]:  # Show first 5
            print(f"        - {missing}")
        if len(diagnostics['validation_files_missing']) > 5:
            print(f"        ... and {len(diagnostics['validation_files_missing']) - 5} more")
    
    figures_dir = output_dir / "figures" / "per_model"
    figures_dir.mkdir(parents=True, exist_ok=True)
    
    # Target dataset name for titles
    target_name = config.get('_target_name', config.get('target_dataset', 'Unknown'))
    
    count = 0
    for scenario_key, models_data in data.items():
        if not models_data:
            continue
            
        scenario_info = SCENARIOS[scenario_key]
        
        # Determine valid distances for this scenario (from first model)
        # We assume most models have same distances
        all_distances = set()
        for m_data in models_data.values():
            all_distances.update(m_data['fixed'].keys())
            all_distances.update(m_data['concurrent'].keys())
        distances = sorted(list(all_distances))
        
        if not distances:
            continue

        print(f"    - {scenario_info['title']} ({len(models_data)} models)")

        for model_name, methods_data in models_data.items():
            # Skip if very few data points
            if len(methods_data['fixed']) < 2 and len(methods_data['concurrent']) < 2:
                continue

            fig, ax = plt.subplots(figsize=(8, 5))
            
            # Plot Fixed
            fixed_d = sorted(methods_data['fixed'].keys())
            fixed_e = [methods_data['fixed'][d] for d in fixed_d]
            if fixed_d:
                ax.plot(fixed_d, fixed_e, marker=MARKERS['fixed'], color=COLORS['fixed'], 
                        label='Fixed-Anchor', linestyle='-', linewidth=2)
            
            # Plot Concurrent
            conc_d = sorted(methods_data['concurrent'].keys())
            conc_e = [methods_data['concurrent'][d] for d in conc_d]
            if conc_d:
                ax.plot(conc_d, conc_e, marker=MARKERS['concurrent'], color=COLORS['concurrent'], 
                        label='Concurrent', linestyle='--', linewidth=2)
                
            # Plot Random Simple
            rand_d = sorted(methods_data['random_simple'].keys())
            rand_e = [methods_data['random_simple'][d] for d in rand_d]
            if rand_d:
                ax.plot(rand_d, rand_e, marker=MARKERS['random_simple'], color=COLORS['random_simple'],
                        label='Random Baseline', linestyle=':', alpha=0.6)

            ax.set_xlabel('Chain Distance')
            ax.set_ylabel('GP-IRT Error (%)')
            ax.set_title(f"{model_name}\n{scenario_info['title']} | Target: {target_name}")
            ax.grid(True, alpha=0.3)
            ax.legend()
            ax.set_xticks(distances)
            
            # Save
            # Sanitize filename
            safe_model_name = "".join([c if c.isalnum() else "_" for c in model_name])
            filename = f"{scenario_key}_model_{safe_model_name}.png"
            fig.savefig(figures_dir / filename, dpi=150, bbox_inches='tight')
            plt.close(fig)
            count += 1
            
    print(f"    ✅ Generated {count} per-model plots in {figures_dir}")


def plot_per_model_combined_grid(output_dir: Path, config: dict, cols_per_row: int = 4):
    """
    Creates a single combined figure per scenario with all models as subplots.
    
    Args:
        output_dir: Path to experiment directory
        config: Config dict with target name etc.
        cols_per_row: Number of columns per row (default: 4)
    """
    print("\n   Generating combined per-model grid plots...")
    
    # Load data
    data, diagnostics = load_per_model_data(output_dir)
    
    if diagnostics['validation_files_found'] == 0:
        print("    ⚠️  No validation files found, skipping combined grid plots")
        return
    
    figures_dir = output_dir / "figures" / "per_model"
    figures_dir.mkdir(parents=True, exist_ok=True)
    
    target_name = config.get('_target_name', config.get('target_dataset', 'Unknown'))
    
    for scenario_key, models_data in data.items():
        if not models_data:
            continue
            
        scenario_info = SCENARIOS[scenario_key]
        
        # Get all distances
        all_distances = set()
        for m_data in models_data.values():
            all_distances.update(m_data['fixed'].keys())
            all_distances.update(m_data['concurrent'].keys())
        distances = sorted(list(all_distances))
        
        if not distances:
            continue
        
        # Filter models with enough data
        valid_models = {
            name: mdata for name, mdata in models_data.items()
            if len(mdata['fixed']) >= 2 or len(mdata['concurrent']) >= 2
        }
        
        if not valid_models:
            continue
        
        # Sort models alphabetically for consistent ordering
        model_names = sorted(valid_models.keys())
        n_models = len(model_names)
        
        # Calculate grid dimensions
        n_rows = (n_models + cols_per_row - 1) // cols_per_row
        
        # Create figure
        fig_width = 4 * cols_per_row
        fig_height = 3 * n_rows
        fig, axes = plt.subplots(n_rows, cols_per_row, figsize=(fig_width, fig_height))
        
        # Flatten axes for easy iteration
        if n_rows == 1 and cols_per_row == 1:
            axes = np.array([[axes]])
        elif n_rows == 1:
            axes = axes.reshape(1, -1)
        elif cols_per_row == 1:
            axes = axes.reshape(-1, 1)
        axes_flat = axes.flatten()
        
        # Plot each model
        for idx, model_name in enumerate(model_names):
            ax = axes_flat[idx]
            methods_data = valid_models[model_name]
            
            # Plot Fixed
            fixed_d = sorted(methods_data['fixed'].keys())
            fixed_e = [methods_data['fixed'][d] for d in fixed_d]
            if fixed_d:
                ax.plot(fixed_d, fixed_e, marker=MARKERS['fixed'], color=COLORS['fixed'], 
                        label='Fixed', linestyle='-', linewidth=1.5, markersize=4)
            
            # Plot Concurrent
            conc_d = sorted(methods_data['concurrent'].keys())
            conc_e = [methods_data['concurrent'][d] for d in conc_d]
            if conc_d:
                ax.plot(conc_d, conc_e, marker=MARKERS['concurrent'], color=COLORS['concurrent'], 
                        label='Conc.', linestyle='--', linewidth=1.5, markersize=4)
                
            # Plot Random Simple
            rand_d = sorted(methods_data['random_simple'].keys())
            rand_e = [methods_data['random_simple'][d] for d in rand_d]
            if rand_d:
                ax.plot(rand_d, rand_e, marker=MARKERS['random_simple'], color=COLORS['random_simple'],
                        label='Random', linestyle=':', alpha=0.6, markersize=3)
            
            # Simplify model name for title (take last part after /)
            short_name = model_name.split('/')[-1]
            if len(short_name) > 25:
                short_name = short_name[:22] + "..."
            
            ax.set_title(short_name, fontsize=8, fontweight='bold')
            ax.grid(True, alpha=0.3)
            ax.tick_params(axis='both', labelsize=7)
            ax.set_xticks(distances)
            ax.set_xticklabels(distances, fontsize=6)
            
            # Only show legend on first subplot
            if idx == 0:
                ax.legend(loc='upper right', fontsize=6)
            
            # Only show y-label on leftmost plots
            if idx % cols_per_row == 0:
                ax.set_ylabel('Error (%)', fontsize=8)
            
            # Only show x-label on bottom plots
            if idx >= (n_rows - 1) * cols_per_row:
                ax.set_xlabel('Distance', fontsize=8)
        
        # Hide unused subplots
        for idx in range(n_models, len(axes_flat)):
            axes_flat[idx].set_visible(False)
        
        # Add main title
        fig.suptitle(f"{scenario_info['title']}\nTarget: {target_name} | {n_models} models", 
                    fontsize=12, fontweight='bold')
        
        plt.tight_layout()
        
        # Save
        filename = f"combined_grid_{scenario_key}.png"
        fig.savefig(figures_dir / filename, dpi=200, bbox_inches='tight')
        plt.close(fig)
        print(f"    ✓ {filename} ({n_models} models, {n_rows}x{cols_per_row} grid)")
